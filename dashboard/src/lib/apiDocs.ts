import { SUPABASE_URL } from "@/lib/config";

export const VERIFY_URL = `${SUPABASE_URL}/functions/v1/verify-transaction`;

/** The text the owner copies and sends to the person building the website. Plain text, so it pastes anywhere
 *  (chat, email, a ticket). The key is only included when the owner chooses to include the one just made. */
export function developerInstructions(key?: string): string {
  const k = key ?? "<YOUR_KEY>";
  return [
    "PayTrace: transaction check API",
    "",
    "Use this from your SERVER only, never from a browser or app a customer can open (the key would be visible).",
    "It tells you whether a transaction ID the customer submitted really arrived in our payment account.",
    "",
    "ENDPOINT",
    `POST ${VERIFY_URL}`,
    "",
    "HEADERS",
    `Authorization: Bearer ${k}`,
    "Content-Type: application/json",
    "",
    "BODY (JSON)",
    '{ "transaction_id": "EXAMPLE123", "provider": "bkash", "amount": 500 }',
    "- transaction_id: required. Spaces and lower case are tidied for you.",
    '- provider: optional. "bkash", "nagad", "rocket" or "upay". Send it whenever you know it.',
    "- amount: optional. The amount the customer says they paid. If you send it, you get amount_matches back.",
    "",
    "ANSWERS",
    '200 {"found": false}                                   -> show UNVERIFIED',
    '200 {"found": true, "provider": "bkash", "amount": 500, "currency": "BDT", "amount_matches": true}',
    "                                                       -> show VERIFIED",
    '   If amount_matches is false -> show AMOUNT MISMATCH. The ID is real but the amount differs;',
    "   the real amount is in the amount field. Never credit more than that amount.",
    '200 {"found": true, "ambiguous": true}                 -> the same ID exists on two providers; send "provider" and ask again',
    "401                                                     -> the key is wrong or was revoked",
    "400                                                     -> bad request (see the error text)",
    "429                                                     -> too many lookups (limit 60 per minute per key); wait a minute",
    "500 / 503 / timeout / no answer                         -> show PENDING CHECK and retry later. Never show UNVERIFIED for these.",
    "",
    "Use a timeout of about 5 seconds.",
    "A payment whose message has not reached PayTrace yet (for example the phone was off) is not found until it arrives,",
    "so a later retry can turn UNVERIFIED into VERIFIED.",
    "Your existing duplicate check stays in place: a found ID may already have been used for another order.",
    "",
    "EXAMPLE (Node 18+, on your server)",
    "async function verifyTransaction(id, claimedAmount) {",
    "  try {",
    `    const res = await fetch("${VERIFY_URL}", {`,
    '      method: "POST",',
    '      headers: { Authorization: "Bearer " + process.env.PAYTRACE_VERIFY_KEY, "Content-Type": "application/json" },',
    "      body: JSON.stringify({ transaction_id: id, amount: claimedAmount }),",
    "      signal: AbortSignal.timeout(5000),",
    "    });",
    '    if (res.status !== 200) return "pending";',
    "    const r = await res.json();",
    '    if (r.found !== true) return "unverified";',
    '    if (r.amount_matches === false) return "amount_mismatch"; // r.amount is what was really received',
    '    return "verified";',
    "  } catch {",
    '    return "pending";',
    "  }",
    "}",
    "",
    "KEEP THE KEY SAFE",
    "Store it in the server's environment settings (for example PAYTRACE_VERIFY_KEY). Do not put it in code that is",
    "committed, in a web page, or in chat. If it leaks, tell the owner: they revoke it on the dashboard and make a new one.",
  ].join("\n");
}

export const GATEWAY_URL = `${SUPABASE_URL}/functions/v1/gateway`;

/** The text the owner sends to the developer who adds PayTrace deposits to a website. */
export function depositInstructions(key?: string): string {
  const k = key ?? "<YOUR_KEY>";
  return [
    "PayTrace: deposit gateway",
    "",
    "Your SERVER creates a deposit order, sends the customer to the pay page it returns, and learns the result by a signed message (webhook)",
    "and/or by asking. Use the key from your server only, never in a browser or app.",
    "",
    "1) CREATE THE ORDER",
    `POST ${GATEWAY_URL}/create-deposit`,
    `Authorization: Bearer ${k}`,
    "Content-Type: application/json",
    '{ "amount": 500, "order_id": "SHOP-1001", "provider": "nagad", "method": "cash_out", "return_url": "https://yourshop.com/thanks", "expires_in_minutes": 15 }',
    "- amount: required, from 500 to 50000 taka.",
    "- order_id: required. YOUR own order number. Sending the same order_id again returns the same order (safe to retry).",
    "- provider: required (\"bkash\", \"nagad\", \"rocket\", \"upay\"). YOUR site shows the deposit methods and lets the customer choose; PayTrace's page starts after that choice.",
    '- method: optional, "send_money" or "cash_out". Use it when you offer both for one provider (for example Nagad Send Money and Nagad Cash Out). Leave it out to accept either.',
    '- If no deposit number is set up for that provider/method you get 409 {"error":"no_wallet"}: hide that method on your page or show a message.',
    "- return_url: optional, https only. The customer is sent back here after a confirmed payment.",
    "- expires_in_minutes: optional, 3 to 60, default 15.",
    '- customer_name, customer_phone: optional, for your own records.',
    'Answer 200: { "tracking_number": "...", "pay_url": "https://.../pay/?trackingNumber=...", "status": "pending", "expires_at": "..." }',
    "Redirect the customer to pay_url. They see the number to pay and paste the TrxID there.",
    "",
    "2) LEARN THE RESULT",
    "a) Webhook (recommended). The owner enters your https address on the dashboard's Websites page and gives you the signing secret.",
    "   PayTrace POSTs JSON: { \"event\": \"deposit.paid\", \"data\": { \"tracking_number\", \"order_id\", \"status\", \"amount\", \"currency\", \"provider\", \"trx_id\", \"paid_at\" } }",
    "   Events: deposit.paid, deposit.review (held for a manual check), deposit.expired, deposit.cancelled.",
    "   Header X-PayTrace-Signature: t=<unix seconds>,v1=<hex>. Compute HMAC-SHA256 with the signing secret over \"<t>.<raw request body>\",",
    "   compare with v1 in constant time, and reject if t is more than 5 minutes old.",
    "   Answer with any 2xx. Anything else is retried (1 min, 5 min, 15 min, 1 h, 3 h, 6 h, 12 h). The same event may arrive twice: handle it idempotently by order_id.",
    "b) Ask. POST " + `${GATEWAY_URL}/order-status`,
    '   { "order_id": "SHOP-1001" }  or  { "tracking_number": "..." }  ->  { "status": "pending|paid|review|expired|cancelled", "amount", "provider", "trx_id", "paid_at", ... }',
    "",
    "ONLY credit the customer when status is \"paid\" and the amount and order_id are the ones you expect. Do not trust the browser redirect.",
    "Errors: 401 wrong or revoked key, 400 bad request (see error text), 409 no deposit number for that method, 429 too many requests (120 per minute per key), 5xx try again.",
  ].join("\n");
}
